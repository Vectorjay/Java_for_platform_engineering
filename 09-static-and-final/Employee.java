public class Employee {

    String name;
    int age;
    String role;
    double salary;
    int experience;

    public Employee(String name,
                    int age,
                    String role,
                    double salary,
                    int experience) {

        this.name = name;
        this.age = age;
        this.role = role;
        this.salary = salary;
        this.experience = experience;

    }

}